def hexc(h, a=255):
    h = h.lstrip('#'); return (int(h[0:2],16), int(h[2:4],16), int(h[4:6],16), a)

def frame(w, h, outline, border_hi, border_lo, fill_top, fill_bot, inner_hi=None, r=3, bw=2):
    im = Image.new("RGBA", (w, h), (0,0,0,0)); px = im.load()
    def inside(x, y, rr, inset):
        x0, y0, x1, y1 = inset, inset, w-1-inset, h-1-inset
        if x < x0 or x > x1 or y < y0 or y > y1: return False
        for cx, cy in ((x0+rr, y0+rr), (x1-rr, y0+rr), (x0+rr, y1-rr), (x1-rr, y1-rr)):
            if (x < x0+rr or x > x1-rr) and (y < y0+rr or y > y1-rr):
                if abs(x-cx) + abs(y-cy) > rr + (0 if rr < 2 else 1): return False
        return True
    for y in range(h):
        for x in range(w):
            if not inside(x, y, r, 0): continue
            if not inside(x, y, max(r-1,0), 1): px[x,y] = hexc(outline); continue
            if not inside(x, y, max(r-1-bw+1,0), 1+bw):
                t = y / max(1, h-1)
                px[x,y] = hexc(border_hi) if t < 0.5 else hexc(border_lo); continue
            t = (y-(1+bw)) / max(1, h-2*(1+bw)-1)
            a, b = hexc(fill_top), hexc(fill_bot)
            px[x,y] = tuple(round(a[i]+(b[i]-a[i])*t) for i in range(4))
    if inner_hi:
        for x in range(2+bw+r-1, w-2-bw-r+1):
            px[x, 1+bw] = hexc(inner_hi)
    return im

